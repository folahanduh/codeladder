/* Critical Moment: a timed attack simulator.
   Pick a built-in scenario or describe your own (generated by the AI coach). An attack
   unfolds live on a virtual machine: identify the attack, decode the evidence, and
   respond in the right order before the clock runs out. Then read the debrief and
   ask the AI coach anything. */
window.CL_CRITICAL = (function () {
  'use strict';

  const $ = (sel, root) => (root || document).querySelector(sel);
  const $$ = (sel, root) => Array.from((root || document).querySelectorAll(sel));
  const esc = (s) => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');
  const CUSTOM_KEY = 'code-ladder-custom-scenarios';
  const LEVEL_NAMES = { beginner: 'Beginner', intermediate: 'Intermediate', advanced: 'Advanced', expert: 'Expert' };
  const SELECTORS = {
    '0x095ea7b3': 'approve(address spender, uint256 amount)',
    '0xa9059cbb': 'transfer(address to, uint256 amount)',
    '0x23b872dd': 'transferFrom(address from, address to, uint256 amount)',
    '0xa22cb465': 'setApprovalForAll(address operator, bool approved)',
    '0xd505accf': 'permit(owner, spender, value, deadline, v, r, s)',
    '0xf2fde38b': 'transferOwnership(address newOwner)',
    '0x40c10f19': 'mint(address to, uint256 amount)',
    '0x8456cb59': 'pause()',
  };

  let timer = null;
  let run = null;
  let api = null;
  function cleanup() { clearInterval(timer); timer = null; run = null; }

  // ------------------------------------------------------------ encoding and decoding
  const toB64 = (s) => btoa(unescape(encodeURIComponent(s)));
  const fromB64 = (s) => {
    let t = s.trim().replace(/-/g, '+').replace(/_/g, '/').replace(/\s+/g, '');
    while (t.length % 4) t += '=';
    return decodeURIComponent(escape(atob(t)));
  };
  const toHex = (s) => [...new TextEncoder().encode(s)].map((b) => b.toString(16).padStart(2, '0')).join('');
  const fromHex = (h) => {
    const clean = h.trim().replace(/^0x/i, '').replace(/\s+/g, '');
    if (!/^[0-9a-f]*$/i.test(clean) || clean.length % 2) throw new Error('not hex');
    return new TextDecoder().decode(new Uint8Array((clean.match(/../g) || []).map((x) => parseInt(x, 16))));
  };
  const b64url = (s) => toB64(s).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
  function encodeEvidence(p) {
    switch (p.encoding) {
      case 'base64': return toB64(p.plaintext);
      case 'hex': return '0x' + toHex(p.plaintext);
      case 'url': return encodeURIComponent(p.plaintext);
      case 'jwt': {
        let payload = p.plaintext;
        try { JSON.parse(payload); } catch (e) { payload = JSON.stringify({ data: p.plaintext }); }
        const sig = b64url(String.fromCharCode(...crypto.getRandomValues(new Uint8Array(32))));
        return `${b64url('{"alg":"HS256","typ":"JWT"}')}.${b64url(payload)}.${sig}`;
      }
      default: return p.plaintext;
    }
  }
  function decodeCalldata(data) {
    const clean = data.trim().toLowerCase();
    if (!/^0x[0-9a-f]{8}/.test(clean)) throw new Error('not calldata');
    const sel = clean.slice(0, 10);
    const words = (clean.slice(10).match(/.{1,64}/g) || []);
    const lines = [`Selector ${sel} = ${SELECTORS[sel] || 'unknown function (look it up in a 4byte signature database)'}`];
    words.forEach((w, i) => {
      let note = '';
      if (/^0{24}[0-9a-f]{40}$/.test(w)) note = `address 0x${w.slice(24)}`;
      else if (/^f{64}$/.test(w)) note = 'maximum uint256 = UNLIMITED amount';
      else { try { note = 'number ' + BigInt('0x' + w).toString(); } catch (e) { note = w; } }
      lines.push(`Argument ${i + 1}: ${note}`);
    });
    return lines.join('\n');
  }
  const DECODERS = [
    { id: 'b64', label: 'Base64 to text', fn: fromB64 },
    { id: 'hex', label: 'Hex to text', fn: fromHex },
    { id: 'url', label: 'URL decode', fn: (s) => decodeURIComponent(s.replace(/\+/g, ' ')) },
    { id: 'jwt', label: 'JWT to JSON', fn: (s) => s.split('.').slice(0, 2).map((x) => JSON.stringify(JSON.parse(fromB64(x)), null, 2)).join('\n') },
    { id: 'calldata', label: 'Decode calldata', fn: decodeCalldata },
  ];

  // ------------------------------------------------------------ validation (AI output is untrusted)
  const str = (v, max) => String(v == null ? '' : v).slice(0, max || 600);
  const slug = (v) => str(v, 40).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'x';
  function normalizeScenario(raw, lessonIds) {
    if (!raw || typeof raw !== 'object') throw new Error('The scenario was empty.');
    const s = {
      id: raw.id ? slug(raw.id) : 'custom-' + Date.now().toString(36),
      title: str(raw.title, 90) || 'Custom scenario',
      level: LEVEL_NAMES[raw.level] ? raw.level : 'intermediate',
      tags: Array.isArray(raw.tags) ? raw.tags.map((t) => str(t, 30)) : [],
      brief: str(raw.brief, 700),
      role: str(raw.role, 120),
      custom: Boolean(raw.custom),
    };
    const scr = raw.screen || {};
    s.screen = {
      kind: ['login', 'wallet', 'terminal', 'email', 'dashboard'].includes(scr.kind) ? scr.kind : 'dashboard',
      title: str(scr.title, 80) || s.title,
      url: str(scr.url, 160),
      lines: (Array.isArray(scr.lines) ? scr.lines : []).slice(0, 8).map((l) => str(l, 160)),
    };
    // actions
    const seen = new Set();
    s.actions = (Array.isArray(raw.actions) ? raw.actions : []).slice(0, 10).map((a) => {
      let id = slug(a.id || a.label);
      while (seen.has(id)) id += '-2';
      seen.add(id);
      return { id, label: str(a.label, 200), correct: Boolean(a.correct), priority: Number(a.priority) || 0, feedback: str(a.feedback, 400) };
    }).filter((a) => a.label);
    const correct = s.actions.filter((a) => a.correct).sort((a, b) => (a.priority || 99) - (b.priority || 99));
    correct.forEach((a, i) => { a.priority = i + 1; });
    s.actions.filter((a) => !a.correct).forEach((a) => { a.priority = 0; });
    if (correct.length < 2 || s.actions.length < 4) throw new Error('The scenario did not include enough response actions.');
    // attack types
    s.attackTypes = (Array.isArray(raw.attackTypes) ? raw.attackTypes : []).slice(0, 6).map((a) => ({ id: slug(a.id || a.label), label: str(a.label, 160) })).filter((a) => a.label);
    s.correctAttackType = slug(raw.correctAttackType);
    if (!s.attackTypes.some((a) => a.id === s.correctAttackType)) {
      if (!s.attackTypes.length) throw new Error('The scenario did not include attack types.');
      s.correctAttackType = s.attackTypes[0].id;
    }
    // events and escalations
    s.events = (Array.isArray(raw.events) ? raw.events : []).slice(0, 20).map((e) => ({
      t: Math.max(0, Math.min(295, Math.round(Number(e.t) || 0))),
      src: slug(e.src).slice(0, 12) || 'log',
      severity: ['info', 'warn', 'bad'].includes(e.severity) ? e.severity : 'info',
      text: str(e.text, 400),
    })).filter((e) => e.text).sort((a, b) => a.t - b.t);
    if (s.events.length < 4) throw new Error('The scenario did not include enough events.');
    const correctIds = new Set(correct.map((a) => a.id));
    s.escalations = (Array.isArray(raw.escalations) ? raw.escalations : []).slice(0, 4).map((x) => ({
      t: Math.max(20, Math.min(295, Math.round(Number(x.t) || 150))),
      preventedBy: slug(x.preventedBy),
      text: str(x.text, 300),
    })).filter((x) => x.text && correctIds.has(x.preventedBy));
    // puzzle
    const pz = raw.puzzle || {};
    s.puzzle = {
      prompt: str(pz.prompt, 300) || 'Decode this piece of evidence.',
      plaintext: str(pz.plaintext, 600),
      encoding: ['base64', 'hex', 'url', 'jwt', 'calldata', 'none'].includes(pz.encoding) ? pz.encoding : 'none',
      question: str(pz.question, 200) || 'What does the evidence reveal?',
      answer: str(pz.answer, 120),
      accept: (Array.isArray(pz.accept) ? pz.accept : []).slice(0, 6).map((a) => str(a, 120)),
    };
    if (!s.puzzle.plaintext || !s.puzzle.answer) throw new Error('The scenario\'s evidence puzzle was incomplete.');
    if (!s.events.some((e) => e.text.includes('{{evidence}}'))) {
      s.events.push({ t: 60, src: 'evidence', severity: 'warn', text: 'Captured evidence: {{evidence}}' });
      s.events.sort((a, b) => a.t - b.t);
    }
    // debrief
    const d = raw.debrief || {};
    const list = (v, n) => (Array.isArray(v) ? v : []).slice(0, n).map((x) => str(x, 300)).filter(Boolean);
    s.debrief = {
      summary: str(d.summary, 1500),
      attackerMethods: list(d.attackerMethods, 8),
      prevention: list(d.prevention, 8),
      script: d.script && d.script.code ? { lang: str(d.script.lang, 12) || 'text', code: str(d.script.code, 2500), explain: str(d.script.explain, 400) } : null,
      lessons: list(d.lessons, 5).filter((id) => !lessonIds || lessonIds.includes(id)),
    };
    return s;
  }

  // ------------------------------------------------------------ storage
  const loadCustom = () => { try { return JSON.parse(localStorage.getItem(CUSTOM_KEY) || '[]'); } catch (e) { return []; } };
  const saveCustom = (list) => { try { localStorage.setItem(CUSTOM_KEY, JSON.stringify(list.slice(0, 6))); } catch (e) { /* ignore */ } };
  const allScenarios = () => [...(window.CL_SCENARIOS || []), ...loadCustom()];
  const lessonList = () => (window.CL_LESSONS || []).filter((l) => ['security', 'keys', 'crypto', 'setup'].includes(l.track)).map((l) => ({ id: l.id, title: l.title }));

  // ------------------------------------------------------------ helpers
  const mmss = (sec) => { const s = Math.max(0, Math.ceil(sec)); return `${String(Math.floor(s / 60)).padStart(2, '0')}:${String(s % 60).padStart(2, '0')}`; };
  const lv = (level) => `<span class="lv lv-${esc(level)}">${esc(LEVEL_NAMES[level] || level)}</span>`;
  const norm = (s) => String(s).toLowerCase().replace(/["'`\s]/g, '');
  function closestScenario(text) {
    const words = new Set(String(text).toLowerCase().split(/[^a-z0-9-]+/).filter((w) => w.length > 2));
    let best = null, score = -1;
    for (const s of window.CL_SCENARIOS || []) {
      const sc = (s.tags || []).filter((t) => words.has(t)).length;
      if (sc > score) { score = sc; best = s; }
    }
    return best;
  }

  // ------------------------------------------------------------ picker view
  function renderPicker(root) {
    cleanup();
    const custom = loadCustom();
    const best = api.getBest ? api.getBest() : {};
    const card = (s) => `<article class="card cm-card">
        <div class="ctf-head">${lv(s.level)}${s.custom ? '<span class="chip">Your scenario</span>' : ''}${best[s.id] != null ? `<span class="ctf-points">Best ${best[s.id]}/100</span>` : ''}</div>
        <h3>${esc(s.title)}</h3>
        <p class="muted small">${esc(s.brief)}</p>
        <div class="row"><button type="button" class="btn btn-primary btn-sm" data-play="${esc(s.id)}">Start</button>${s.custom ? `<button type="button" class="btn btn-sm" data-forget="${esc(s.id)}">Remove</button>` : ''}</div>
      </article>`;
    root.innerHTML = `
      <section class="card cm-make">
        <div class="cm-make-head"><div><p class="eyebrow">Create any scenario</p><h2 class="section-title">Describe a situation and the AI builds it</h2></div><span class="chip" id="cmAiStatus">Checking AI...</span></div>
        <label class="field"><span class="field-label">Your scenario</span>
          <textarea id="cmDesc" rows="3">I am logging in to a test dev account and someone is trying to intercept my account and details. Give me 5 minutes to decipher the code and stop the attack.</textarea></label>
        <div class="row">
          <label class="field" style="grid-auto-flow:column;align-items:center;gap:8px"><span class="field-label">Level</span>
            <select id="cmLevel">${Object.entries(LEVEL_NAMES).map(([k, v]) => `<option value="${k}"${k === 'intermediate' ? ' selected' : ''}>${v}</option>`).join('')}</select></label>
          <button type="button" class="btn btn-primary" id="cmGenerate">Generate scenario</button>
        </div>
        <div id="cmGenOut" role="status"></div>
      </section>
      <div class="row">
        <label class="field" style="grid-auto-flow:column;align-items:center;gap:8px"><span class="field-label">Time limit</span>
          <select id="cmDuration"><option value="180">3 minutes</option><option value="300" selected>5 minutes</option><option value="600">10 minutes</option></select></label>
        <span class="muted small">Each run: identify the attack, decode the evidence, respond in the right order. Wrong actions cost 15 seconds.</span>
      </div>
      ${custom.length ? `<section class="section"><h2 class="section-title">Your scenarios</h2><div class="grid-3">${custom.map(card).join('')}</div></section>` : ''}
      <section class="section"><h2 class="section-title">Built-in scenarios</h2><div class="grid-3">${(window.CL_SCENARIOS || []).map(card).join('')}</div></section>`;

    const status = $('#cmAiStatus', root);
    window.CL_AI.ready.then((m) => {
      status.textContent = m === 'off' ? 'AI not connected' : 'AI connected';
      status.classList.toggle('chip-good', m !== 'off');
    });
    $$('[data-play]', root).forEach((b) => b.addEventListener('click', () => start(root, b.dataset.play)));
    $$('[data-forget]', root).forEach((b) => b.addEventListener('click', () => { saveCustom(loadCustom().filter((s) => s.id !== b.dataset.forget)); renderPicker(root); }));
    $('#cmGenerate', root).addEventListener('click', async () => {
      const desc = $('#cmDesc', root).value.trim();
      const out = $('#cmGenOut', root);
      const btn = $('#cmGenerate', root);
      if (!desc) { out.innerHTML = '<p class="muted">Describe a scenario first.</p>'; return; }
      btn.disabled = true;
      out.innerHTML = '<p class="muted">Designing your scenario. This usually takes 20 to 60 seconds...</p>';
      try {
        const raw = await window.CL_AI.generateScenario(desc, $('#cmLevel', root).value, lessonList());
        const s = normalizeScenario({ ...raw, custom: true, tags: desc.toLowerCase().split(/\W+/).slice(0, 20) }, (window.CL_LESSONS || []).map((l) => l.id));
        saveCustom([s, ...loadCustom()]);
        api.toast && api.toast('Scenario ready');
        renderPicker(root);
        start(root, s.id);
      } catch (e) {
        const near = closestScenario(desc);
        out.innerHTML = `<div class="fb ${e.code === 'off' ? 'fb-ghost' : 'fb-bad'}"><p>${esc(e.message || 'The scenario could not be generated.')}</p>${e.code === 'off' ? '<p>Custom scenarios need the AI coach: run Code Ladder on your computer with <code>npm install</code> and <code>ANTHROPIC_API_KEY=your-key npm start</code>, or use the claude.ai version.</p>' : ''}${near ? `<p>The closest built-in scenario is <strong>${esc(near.title)}</strong>.</p><div class="row"><button type="button" class="btn btn-sm btn-primary" data-near="${esc(near.id)}">Play it now</button></div>` : ''}</div>`;
        const nb = $('[data-near]', out);
        if (nb) nb.addEventListener('click', () => start(root, nb.dataset.near));
      } finally {
        btn.disabled = false;
      }
    });
  }

  // ------------------------------------------------------------ run view
  function start(root, id) {
    cleanup();
    const sc = allScenarios().find((s) => s.id === id);
    if (!sc) return;
    const durationSel = $('#cmDuration', root);
    const duration = durationSel ? Number(durationSel.value) : 300;
    const evidence = encodeEvidence(sc.puzzle);
    run = {
      sc, duration, evidence, scale: duration / 300, elapsed: 0, last: performance.now(), paused: false, ended: false,
      shown: new Set(), fired: new Set(), blocked: new Set(),
      identify: { tries: 0, done: false, correct: false },
      puzzle: { tries: 0, done: false, correct: false },
      taken: [], wrong: [], log: [],
    };
    const correctCount = sc.actions.filter((a) => a.correct).length;
    root.innerHTML = `
      <div class="cm-run">
        <div class="cm-title"><p class="eyebrow">Critical Moment &middot; ${esc(LEVEL_NAMES[sc.level])}</p><h2>${esc(sc.title)}</h2></div>
        <div class="cm-top">
          <div class="cm-clock"><span class="cm-time" id="cmTime">${mmss(duration)}</span><div class="bar"><span id="cmBar" style="width:100%"></span></div></div>
          <div class="row"><button type="button" class="btn btn-sm" id="cmPause">Pause</button><button type="button" class="btn btn-sm" id="cmEnd">End and debrief</button></div>
          <button type="button" class="cm-ticker" id="cmTicker" aria-label="Latest attacker activity. Jump to the live feed"><span class="cm-ticker-text">Waiting for activity...</span></button>
        </div>
        <p class="cm-brief"><strong>You are:</strong> ${esc(sc.role)}. ${esc(sc.brief)}</p>
        <div class="cm-grid">
          <section class="vm vm-${esc(sc.screen.kind)}" aria-label="Your virtual machine">
            <div class="vm-bar"><span class="vm-dots" aria-hidden="true"><i></i><i></i><i></i></span><span class="vm-title">${esc(sc.screen.title)}</span><span class="vm-tag">VM</span></div>
            ${sc.screen.url ? `<div class="vm-url"><span class="${/^http:\/\//.test(sc.screen.url) ? 'vm-insecure' : 'vm-secure'}">${/^http:\/\//.test(sc.screen.url) ? 'Not secure' : 'Secure'}</span><span class="vm-addr">${esc(sc.screen.url)}</span></div>` : ''}
            <div class="vm-body">${sc.screen.lines.map((l) => `<div class="vm-line">${esc(l)}</div>`).join('')}</div>
          </section>
          <section class="feed" aria-label="Attacker activity">
            <div class="feed-head"><span><span class="feed-dot" aria-hidden="true"></span>Live activity</span><span class="muted small" id="cmCount">0 events</span></div>
            <div class="feed-log" id="cmFeed" role="log" aria-live="polite"></div>
          </section>
        </div>
        <div class="cm-tasks">
          <section class="card cm-task" id="cmIdentify">
            <p class="cm-step">1 &middot; Identify the attack</p>
            <div class="cm-opts">${sc.attackTypes.map((a) => `<label class="quiz-opt"><input type="radio" name="cmType" value="${esc(a.id)}"><span>${esc(a.label)}</span></label>`).join('')}</div>
            <div class="row"><button type="button" class="btn btn-sm btn-primary" id="cmLock">Lock in</button></div>
            <p class="cm-msg" id="cmIdMsg" role="status"></p>
          </section>
          <section class="card cm-task" id="cmPuzzle">
            <p class="cm-step">2 &middot; Decipher the evidence</p>
            <p class="small">${esc(sc.puzzle.prompt)}</p>
            <label class="field"><span class="field-label">Evidence (paste anything here to decode it)</span><textarea class="mono" id="cmEvidence" rows="3" spellcheck="false"></textarea></label>
            <div class="row cm-decoders">${DECODERS.map((d) => `<button type="button" class="btn btn-sm" data-decode="${d.id}">${d.label}</button>`).join('')}</div>
            <pre class="hash-out cm-decoded" id="cmDecoded">Decoded output appears here.</pre>
            <label class="field"><span class="field-label">${esc(sc.puzzle.question)}</span><input type="text" id="cmAnswer" autocomplete="off" spellcheck="false"></label>
            <div class="row"><button type="button" class="btn btn-sm btn-primary" id="cmCheck">Check</button></div>
            <p class="cm-msg" id="cmPzMsg" role="status"></p>
          </section>
          <section class="card cm-task" id="cmRespond">
            <p class="cm-step">3 &middot; Respond <span class="muted small" id="cmActCount">0 of ${correctCount} key steps</span></p>
            <div class="cm-actions">${shuffle(sc.actions).map((a) => `<button type="button" class="cm-action" data-act="${esc(a.id)}">${esc(a.label)}</button>`).join('')}</div>
            <p class="cm-msg" id="cmActMsg" role="status"></p>
          </section>
        </div>
        <section class="cm-coach card" id="cmCoachWrap"><div id="cmCoach"></div></section>
      </div>`;
    $('#cmEvidence', root).value = evidence;
    wireRun(root);
    window.CL_AI.mountCoach($('#cmCoach', root), {
      title: 'AI coach',
      intro: 'I can see what you see. Ask me what a log line means, what an attack technique is, or for a hint. I will not just hand you the answers while the clock is running, unless you ask me to.',
      suggestions: ['What does the latest event mean?', 'Give me a hint for the attack type', 'How do I decode this evidence?'],
      getContext: () => coachContext(),
    });
    timer = setInterval(() => tick(root), 250);
    tick(root);
    root.scrollIntoView({ block: 'start' });
  }

  function shuffle(list) {
    const a = list.slice();
    for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(Math.random() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; }
    return a;
  }

  function feed(root, t, src, text, cls) {
    const log = $('#cmFeed', root);
    if (!log) return;
    const line = document.createElement('div');
    line.className = `feed-line sev-${cls}`;
    line.innerHTML = `<span class="feed-t">${mmss(t)}</span><span class="feed-src">${esc(src)}</span><span class="feed-text">${esc(text)}</span>`;
    log.append(line);
    log.scrollTop = log.scrollHeight;
    run.log.push({ t, src, text, cls });
    const tk = $('#cmTicker', root);
    if (tk) {
      tk.className = `cm-ticker sev-${cls}`;
      tk.firstElementChild.textContent = `${mmss(t)} ${src.toUpperCase()}  ${text}`;
    }
    const c = $('#cmCount', root);
    if (c) c.textContent = `${run.log.length} event${run.log.length === 1 ? '' : 's'}`;
  }

  function tick(root) {
    if (!run || run.ended) return;
    const now = performance.now();
    if (!run.paused) run.elapsed += (now - run.last) / 1000;
    run.last = now;
    const { sc } = run;
    sc.events.forEach((e, i) => {
      if (!run.shown.has(i) && run.elapsed >= e.t * run.scale) {
        run.shown.add(i);
        feed(root, e.t * run.scale, e.src, e.text.replace(/\{\{evidence\}\}/g, run.evidence), e.severity);
      }
    });
    sc.escalations.forEach((x, i) => {
      if (!run.fired.has(i) && !run.blocked.has(i) && run.elapsed >= x.t * run.scale) {
        if (run.taken.includes(x.preventedBy)) {
          run.blocked.add(i);
          const a = sc.actions.find((y) => y.id === x.preventedBy);
          feed(root, run.elapsed, 'blocked', `Attempt blocked: your earlier action "${a ? a.label : x.preventedBy}" stopped the attacker here.`, 'good');
        } else {
          run.fired.add(i);
          feed(root, run.elapsed, 'escalation', x.text, 'esc');
        }
      }
    });
    const left = run.duration - run.elapsed;
    const t = $('#cmTime', root);
    if (t) { t.textContent = mmss(left); t.classList.toggle('cm-urgent', left <= 60); }
    const bar = $('#cmBar', root);
    if (bar) bar.style.width = `${Math.max(0, (left / run.duration) * 100)}%`;
    if (left <= 0) end(root, 'time');
  }

  function wireRun(root) {
    const { sc } = run;
    $('#cmPause', root).addEventListener('click', (e) => {
      tick(root);
      run.paused = !run.paused;
      e.target.textContent = run.paused ? 'Resume' : 'Pause';
      $('.cm-run', root).classList.toggle('is-paused', run.paused);
    });
    $('#cmEnd', root).addEventListener('click', () => end(root, 'manual'));
    $('#cmTicker', root).addEventListener('click', () => $('.feed', root).scrollIntoView({ behavior: 'smooth', block: 'center' }));
    // identify
    $('#cmLock', root).addEventListener('click', () => {
      if (run.identify.done) return;
      const pick = $('input[name="cmType"]:checked', root);
      const msg = $('#cmIdMsg', root);
      if (!pick) { msg.textContent = 'Choose an attack type first.'; return; }
      run.identify.tries++;
      if (pick.value === sc.correctAttackType) {
        run.identify.done = run.identify.correct = true;
        msg.innerHTML = '<strong class="ok">Correct.</strong> That is what the evidence shows.';
        lockSection(root, '#cmIdentify');
        feed(root, run.elapsed, 'you', `Identified the attack: ${sc.attackTypes.find((a) => a.id === pick.value).label}`, 'you');
      } else if (run.identify.tries >= 2) {
        run.identify.done = true;
        const right = sc.attackTypes.find((a) => a.id === sc.correctAttackType);
        msg.innerHTML = `<strong class="bad">Not this one.</strong> It was: ${esc(right.label)}.`;
        lockSection(root, '#cmIdentify');
      } else {
        msg.innerHTML = '<strong class="bad">Not quite.</strong> Reread the newest events: where is the attacker positioned, and what are they stealing? One more try.';
      }
      maybeFinish(root);
    });
    // decoders
    $$('[data-decode]', root).forEach((b) => b.addEventListener('click', () => {
      const d = DECODERS.find((x) => x.id === b.dataset.decode);
      const out = $('#cmDecoded', root);
      try { out.textContent = d.fn($('#cmEvidence', root).value); }
      catch (e) { out.textContent = `That does not look like ${d.label.split(' ')[0]} data. Try another decoder.`; }
    }));
    // puzzle
    const check = () => {
      if (run.puzzle.done) return;
      const v = $('#cmAnswer', root).value;
      const msg = $('#cmPzMsg', root);
      if (!v.trim()) { msg.textContent = 'Type your answer first.'; return; }
      run.puzzle.tries++;
      const answers = [sc.puzzle.answer, ...(sc.puzzle.accept || [])].map(norm).filter(Boolean);
      const ok = answers.some((a) => norm(v) === a || norm(v).includes(norm(sc.puzzle.answer)));
      if (ok) {
        run.puzzle.done = run.puzzle.correct = true;
        msg.innerHTML = '<strong class="ok">Decoded.</strong> You can see exactly what the attacker is after.';
        lockSection(root, '#cmPuzzle', true);
        feed(root, run.elapsed, 'you', 'Decoded the evidence.', 'you');
      } else if (run.puzzle.tries >= 3) {
        run.puzzle.done = true;
        msg.innerHTML = `<strong class="bad">Out of tries.</strong> The answer was <code>${esc(sc.puzzle.answer)}</code>.`;
        lockSection(root, '#cmPuzzle', true);
      } else {
        msg.innerHTML = `<strong class="bad">Not yet.</strong> Try a different decoder on the evidence. ${3 - run.puzzle.tries} ${3 - run.puzzle.tries === 1 ? 'try' : 'tries'} left.`;
      }
      maybeFinish(root);
    };
    $('#cmCheck', root).addEventListener('click', check);
    $('#cmAnswer', root).addEventListener('keydown', (e) => { if (e.key === 'Enter') check(); });
    // actions
    $$('[data-act]', root).forEach((b) => b.addEventListener('click', () => {
      if (run.ended || run.taken.includes(b.dataset.act) || run.wrong.includes(b.dataset.act)) return;
      const a = sc.actions.find((x) => x.id === b.dataset.act);
      const msg = $('#cmActMsg', root);
      b.disabled = true;
      if (a.correct) {
        run.taken.push(a.id);
        b.classList.add('is-good');
        msg.innerHTML = `<strong class="ok">Good move.</strong> ${esc(a.feedback)}`;
        feed(root, run.elapsed, 'you', a.label, 'you');
      } else {
        run.wrong.push(a.id);
        b.classList.add('is-bad');
        run.elapsed += 15;
        tick(root);
        const clock = $('#cmTime', root);
        clock.classList.add('cm-penalty');
        setTimeout(() => clock.classList.remove('cm-penalty'), 650);
        msg.innerHTML = `<strong class="bad">That made it worse (-15 seconds).</strong> ${esc(a.feedback)}`;
        feed(root, run.elapsed, 'you', `${a.label} (mistake)`, 'mistake');
      }
      $('#cmActCount', root).textContent = `${run.taken.length} of ${sc.actions.filter((x) => x.correct).length} key steps`;
      maybeFinish(root);
    }));
  }

  function lockSection(root, sel, keepInputs) {
    $$(`${sel} input, ${sel} button`, root).forEach((el) => {
      if (keepInputs && (el.dataset.decode || el.id === 'cmEvidence')) return;
      el.disabled = true;
    });
  }

  function maybeFinish(root) {
    const all = run.sc.actions.filter((a) => a.correct).every((a) => run.taken.includes(a.id));
    if (run.identify.done && run.puzzle.done && all) end(root, 'contained');
  }

  function score() {
    const { sc } = run;
    const correct = sc.actions.filter((a) => a.correct);
    const parts = [];
    const id = run.identify.correct ? (run.identify.tries === 1 ? 20 : 10) : 0;
    parts.push({ label: 'Identified the attack', got: id, max: 20 });
    const pz = run.puzzle.correct ? [0, 20, 14, 8][run.puzzle.tries] || 8 : 0;
    parts.push({ label: 'Decoded the evidence', got: pz, max: 20 });
    const resp = Math.max(0, Math.round((45 * run.taken.length) / Math.max(1, correct.length)) - 5 * run.wrong.length);
    parts.push({ label: `Response steps (${run.taken.length}/${correct.length}, ${run.wrong.length} mistake${run.wrong.length === 1 ? '' : 's'})`, got: resp, max: 45 });
    const first = run.taken[0] && correct.find((a) => a.id === run.taken[0]);
    parts.push({ label: 'Started with the most urgent step', got: first && first.priority === 1 ? 5 : 0, max: 5 });
    const total = sc.escalations.length;
    let prevented = total;
    if (total) {
      prevented = sc.escalations.filter((x, i) => !run.fired.has(i) && (run.blocked.has(i) || run.taken.includes(x.preventedBy))).length;
    }
    parts.push({ label: `Escalations prevented (${prevented}/${total || 0})`, got: total ? Math.round((10 * prevented) / total) : 10, max: 10 });
    const sum = parts.reduce((n, p) => n + p.got, 0);
    return { parts, total: Math.min(100, sum) };
  }

  function end(root, why) {
    if (!run || run.ended) return;
    run.ended = true;
    clearInterval(timer);
    timer = null;
    const { sc } = run;
    const sres = score();
    const outcome = sres.total >= 85 ? ['Attack contained', 'good'] : sres.total >= 60 ? ['Partly contained', 'warn'] : ['Breach', 'bad'];
    if (api.saveScore) api.saveScore(sc.id, sres.total);
    const correct = sc.actions.filter((a) => a.correct).sort((a, b) => a.priority - b.priority);
    const timeline = run.log.map((l) => `<li class="sev-${l.cls}"><span class="feed-t">${mmss(l.t)}</span> <strong>${esc(l.src)}</strong> ${esc(l.text)}</li>`).join('');
    const why2 = { time: 'Time ran out.', manual: 'You ended the run.', contained: 'You completed every task before time ran out.' }[why];
    const lessons = (sc.debrief.lessons || []).map((id) => (window.CL_LESSONS || []).find((l) => l.id === id)).filter(Boolean);
    const tasks = $('.cm-tasks', root);
    const debrief = document.createElement('section');
    debrief.className = 'cm-debrief';
    debrief.innerHTML = `
      <div class="card cm-result cm-${outcome[1]}">
        <div class="cm-score"><b>${sres.total}</b><span>/ 100</span></div>
        <div><p class="eyebrow">Debrief</p><h2 class="section-title">${outcome[0]}</h2><p class="muted">${why2} ${escalationNote(sres)}</p></div>
        <div class="row"><button type="button" class="btn btn-primary btn-sm" id="cmAgain">Try again</button><button type="button" class="btn btn-sm" id="cmPick">Choose another scenario</button></div>
      </div>
      <div class="grid-2">
        <div class="card cm-breakdown"><h3 class="small-title">Score breakdown</h3>${sres.parts.map((p) => `<div class="cm-part"><span>${esc(p.label)}</span><b>${p.got}/${p.max}</b></div>`).join('')}</div>
        <div class="card"><h3 class="small-title">What happened</h3><p>${esc(sc.debrief.summary)}</p></div>
      </div>
      <div class="grid-2">
        <div class="card"><h3 class="small-title">Methods the attacker used</h3><ul class="plain-list">${sc.debrief.attackerMethods.map((m) => `<li>${esc(m)}</li>`).join('')}</ul></div>
        <div class="card"><h3 class="small-title">The professional response, in order</h3><ol class="plain-list">${correct.map((a) => `<li>${run.taken.includes(a.id) ? '<span class="ok">&#10003;</span> ' : '<span class="bad">&#10007;</span> '}${esc(a.label)}</li>`).join('')}</ol>${run.wrong.length ? `<p class="small muted" style="margin-top:8px">Mistakes: ${run.wrong.map((w) => esc(sc.actions.find((a) => a.id === w).label)).join('; ')}</p>` : ''}</div>
      </div>
      <div class="card"><h3 class="small-title">How to stop this happening again</h3><ul class="plain-list">${sc.debrief.prevention.map((m) => `<li>${esc(m)}</li>`).join('')}</ul></div>
      ${sc.debrief.script ? `<div class="card cm-script"><h3 class="small-title">A script that helps</h3><div class="code" data-lang="${esc(sc.debrief.script.lang)}"><pre><code class="language-${esc(sc.debrief.script.lang)}">${esc(sc.debrief.script.code)}</code></pre></div><p class="muted small">${esc(sc.debrief.script.explain)}</p></div>` : ''}
      <details class="card"><summary class="small-title">Full timeline (${run.log.length} entries)</summary><ol class="cm-timeline">${timeline}</ol></details>
      ${lessons.length ? `<div class="card"><h3 class="small-title">Lessons that cover this</h3><ul class="plain-list">${lessons.map((l) => `<li><a href="#lesson-${l.id}">${esc(l.title)}</a></li>`).join('')}</ul></div>` : ''}`;
    tasks.replaceWith(debrief);
    $('#cmPause', root).disabled = true;
    $('#cmEnd', root).disabled = true;
    if (api.enhanceCode) api.enhanceCode(debrief);
    $('#cmAgain', root).addEventListener('click', () => start(root, sc.id));
    $('#cmPick', root).addEventListener('click', () => renderPicker(root));
    feed(root, run.elapsed, 'system', `Run ended: ${outcome[0]} (${sres.total}/100).`, 'you');
    debrief.scrollIntoView({ behavior: 'smooth', block: 'start' });
  }

  function escalationNote() {
    const total = run.sc.escalations.length;
    if (!total) return '';
    if (run.fired.size) return `${run.fired.size} of the attacker's ${total} escalations happened before you stopped ${run.fired.size > 1 ? 'them' : 'it'}.`;
    const covered = run.sc.escalations.filter((x, i) => run.blocked.has(i) || run.taken.includes(x.preventedBy)).length;
    if (covered === total) return 'Every escalation the attacker tried was blocked.';
    return `The attacker had not escalated yet, but ${total - covered} of their next ${total} moves would still have worked.`;
  }

  function coachContext() {
    if (!run) return '';
    const { sc } = run;
    const lines = [
      `Critical Moment simulator. Scenario: "${sc.title}" (${sc.level}). Learner's role: ${sc.role}. Brief: ${sc.brief}`,
      `What the learner's virtual machine shows: ${sc.screen.title} ${sc.screen.url} | ${sc.screen.lines.join(' | ')}`,
      `Time used: ${mmss(run.elapsed)} of ${mmss(run.duration)}.`,
      'Events the learner has seen so far:',
      ...run.log.map((l) => `[${mmss(l.t)}] ${l.src}: ${l.text}`),
      `Attack-type options: ${sc.attackTypes.map((a) => a.label).join('; ')}`,
      `Evidence puzzle: ${sc.puzzle.prompt} Question: ${sc.puzzle.question} Encoded evidence: ${run.evidence}`,
      `Response options: ${sc.actions.map((a) => a.label).join('; ')}`,
      `Actions taken so far: ${run.taken.join(', ') || 'none'}; mistakes: ${run.wrong.join(', ') || 'none'}.`,
    ];
    if (run.ended) {
      lines.push(
        'THE RUN HAS ENDED. You may now explain everything fully, including the answers and why each choice was right or wrong.',
        `Correct attack type: ${sc.attackTypes.find((a) => a.id === sc.correctAttackType).label}. Decoded evidence: ${sc.puzzle.plaintext} (answer: ${sc.puzzle.answer}).`,
        `Correct actions in order: ${sc.actions.filter((a) => a.correct).sort((a, b) => a.priority - b.priority).map((a) => a.label).join(' > ')}`,
        `Debrief: ${sc.debrief.summary}`,
      );
    } else {
      lines.push('THE RUN IS STILL IN PROGRESS. Coach rather than solve: explain concepts and what the evidence means, and give hints. Only name the attack type, the decoded answer or the correct actions if the learner explicitly asks you for the answer.');
    }
    return lines.join('\n');
  }

  function mount(root, apiIn) {
    api = apiIn || {};
    renderPicker(root);
  }

  return { mount, cleanup, normalizeScenario, encodeEvidence, decodeCalldata, closestScenario };
})();
